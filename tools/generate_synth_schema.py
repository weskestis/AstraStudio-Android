#!/usr/bin/env python3
"""Generate the C++/Kotlin patch wire contract from one reviewed schema."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
schema = json.loads((root / 'tools/synth-schema.json').read_text())
params = schema['parameters']
header = ['// Generated by tools/generate_synth_schema.py; edit synth-schema.json.', '#pragma once', '#include <array>', 'namespace astra::synth {', 'enum Param : int {']
for i,p in enumerate(params): header.append(f'    {p[0]} = {i},')
header += [f'    ParameterCount = {len(params)}', '};', 'struct ParamSpec { float minimum, maximum, initial; bool integer; };', 'inline constexpr std::array<ParamSpec, ParameterCount> specs{{']
def cpp(v): return f'{float(v):.9g}' + ('.0' if float(v).is_integer() else '') + 'f'
for p in params: header.append('    {' + ', '.join([cpp(p[2]), cpp(p[3]), cpp(p[4]), str(p[5]).lower()]) + '},')
header += ['}};', f'inline constexpr int kPresetCount = {len(schema["presets"])};', 'inline constexpr std::array<const char*, kPresetCount> presetNames{{']
header += [f'    "{p}",' for p in schema['presets']]
header += ['}};', '} // namespace astra::synth', '']
(root/'app/src/main/cpp/dsp/ParameterIds.h').write_text('\n'.join(header))
k = ['// Generated by tools/generate_synth_schema.py; edit synth-schema.json.', 'package com.weskestis.astrastudio.synth', '', 'data class ParamInfo(val name: String, val minimum: Float, val maximum: Float, val initial: Float, val integer: Boolean, val logarithmic: Boolean)', 'object SynthSchema {']
for i,p in enumerate(params): k.append(f'    const val {p[0]} = {i}')
k += [f'    const val PARAM_COUNT = {len(params)}', '    const val LFO_POINTS = 32', '    const val MOD_SLOTS = 16', '    const val WIRE_COUNT = PARAM_COUNT + 4 * LFO_POINTS + 3 * MOD_SLOTS', '    val parameters = listOf(']
for p in params: k.append(f'        ParamInfo("{p[1]}", {cpp(p[2])}, {cpp(p[3])}, {cpp(p[4])}, {str(p[5]).lower()}, {str(p[6]).lower()}),')
k += ['    )', '    val presets = listOf(' + ', '.join(json.dumps(n) for n in schema['presets']) + ')', '}', '']
(root/'app/src/main/java/com/weskestis/astrastudio/synth/SynthSchema.kt').write_text('\n'.join(k))
