#!/usr/bin/env python3
"""Keep project, DSP and JNI dimensions consistent across Kotlin and C++."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
s=json.loads((root/'tools/capacity-schema.json').read_text())
assert 1<=s['tracks']<=64 and 1<=s['scenes']<=32
pairs=[('TRACKS','kTrackCount',s['tracks']),('SCENES','kSceneCount',s['scenes']),('CLIPS','kClipCount',s['tracks']*s['scenes']),('REGIONS','kRegionCount',s['regions']),('NATIVE_VALUES','kProjectWireLimit',s['nativeValues']),('JSON_BYTES','kProjectJsonBytes',s['projectJsonBytes']),('SEQUENCE_VALUES','kSequenceValues',s['tracks']*3+1),('FX_VALUES','kFxValues',s['tracks']*4+69)]
h=['// Generated by tools/generate_capacity_schema.py.','#pragma once','namespace astra {']
h += [f'inline constexpr int {cpp} = {v};' for _,cpp,v in pairs]
h += ['}','']
k=['// Generated by tools/generate_capacity_schema.py.','package com.weskestis.astrastudio.project','','object ProjectLimits {']
k += [f'    const val {kt} = {v}' for kt,_,v in pairs]
k += ['}','']
(root/'app/src/main/cpp/core/Limits.h').write_text('\n'.join(h))
(root/'app/src/main/java/com/weskestis/astrastudio/project/ProjectLimits.kt').write_text('\n'.join(k))
